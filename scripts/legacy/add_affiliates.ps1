$updated = @()
$skipped = @()

foreach ($filename in $affiliates.Keys) {
    $filepath = Join-Path $dir $filename
    if (Test-Path $filepath) {
        $existing = Get-Content $filepath -Raw
        if ($existing -match "tag=errorcodefixes-20") {
            $skipped += $filename
            Write-Host "SKIP (already has affiliate links): $filename"
        } else {
            $section = $affiliates[$filename]
            Add-Content -Path $filepath -Value $section -NoNewline
            $updated += $filename
            Write-Host "UPDATED: $filename"
        }
    } else {
        Write-Host "NOT FOUND: $filepath"
        $skipped += "MISSING: $filename"
    }
}

Write-Host "`n=== SUMMARY ===" 
Write-Host "Updated: $($updated.Count) files"
Write-Host "Skipped: $($skipped.Count) files"
$updated | ForEach-Object { Write-Host "  + $_" }
